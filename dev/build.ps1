# Package the LIES mod for a game test.
# Dev-only files (dev/, .git/, dist/) are excluded.
# The user copies dist/LIES into the game; this script never touches the game.

$ErrorActionPreference = 'Stop'
$RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$DistRoot = Join-Path $RepoRoot 'dist'
$Dest = Join-Path $DistRoot 'LIES'
$Marker = Join-Path $Dest '.lies-build'

if (Test-Path $Dest) {
    if (-not (Test-Path $Marker)) {
        throw "Refusing to delete $Dest because it has no .lies-build marker. Move it to _archive or remove it manually."
    }
    Remove-Item -LiteralPath $Dest -Recurse -Force
}

New-Item -ItemType Directory -Force $Dest | Out-Null

$items = @('mod.txt', 'menumanager.lua', 'menunodegui.lua', 'logo.png', 'LICENSE', 'loc', 'lua', 'menu')
foreach ($item in $items) {
    $source = Join-Path $RepoRoot $item
    if (-not (Test-Path -LiteralPath $source)) {
        throw "Missing runtime item: $item"
    }
    Copy-Item -LiteralPath $source -Destination $Dest -Recurse -Force
}

$commit = (& git -C $RepoRoot rev-parse --short HEAD 2>$null)
if (-not $commit) { $commit = 'unknown' }
$markerText = @(
    'Generated by dev/build.ps1',
    ('commit: ' + $commit),
    ('built: ' + (Get-Date).ToString('u'))
) -join "`n"
Set-Content -LiteralPath $Marker -Value $markerText -Encoding utf8

Write-Host "built $Dest"
Write-Host "commit: $commit"
Write-Host ''
Write-Host 'Copy to the game (user action):'
Write-Host ('  Copy-Item -LiteralPath ''{0}'' -Destination ''C:\Program Files (x86)\Steam\steamapps\common\PAYDAY 2\mods\LIES'' -Recurse -Force' -f $Dest)
Write-Host ''
Write-Host 'Optional test harness:'
Write-Host ('  Copy-Item -LiteralPath ''{0}'' -Destination ''C:\Program Files (x86)\Steam\steamapps\common\PAYDAY 2\mods\LIES-TestHarness'' -Recurse -Force' -f (Join-Path $RepoRoot 'dev\test-harness'))
